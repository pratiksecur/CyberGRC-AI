@router.get(
    "/{evidence_id}/file",
)
def download_evidence_file(
    evidence_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(
        require_permission(
            "evidence",
            "view",
        )
    ),
):
    """
    Securely retrieve an evidence file.

    The file is returned only after the evidence resource
    itself has passed the user's visibility check.
    """

    visible_user_ids = get_visible_user_ids(
        db,
        current_user,
        "evidence",
    )

    evidence = (
        db.query(Evidence)
        .join(
            Control,
            Evidence.control_id
            == Control.id,
        )
        .filter(
            Evidence.id == evidence_id,
            Control.owner_id.in_(
                visible_user_ids
            ),
        )
        .first()
    )

    if evidence is None:
        raise HTTPException(
            status_code=404,
            detail="Evidence not found.",
        )

    file_path = Path(
        evidence.file_path
    )

    if not file_path.is_absolute():
        file_path = Path.cwd() / file_path

    upload_root = (
        UPLOAD_DIR.resolve()
    )

    try:
        resolved_path = (
            file_path.resolve()
        )

        resolved_path.relative_to(
            upload_root
        )

    except ValueError:
        raise HTTPException(
            status_code=404,
            detail="Evidence file not found.",
        )

    if not resolved_path.is_file():
        raise HTTPException(
            status_code=404,
            detail="Evidence file not found.",
        )

    return FileResponse(
        path=resolved_path,
        filename=evidence.file_name,
        media_type="application/octet-stream",
        content_disposition_type="attachment",
        headers={
            "X-Content-Type-Options": "nosniff",
            "Cache-Control": (
                "private, no-store"
            ),
        },
    )


@router.patch(
    "/{evidence_id}",
    response_model=EvidenceResponse,
)
def update_existing_evidence(
    evidence_id: int,
    evidence_data: EvidenceUpdate,
    db: Session = Depends(get_db),
    current_user: User = Depends(
        require_permission(
            "evidence",
            "update",
        )
    ),
):
    visible_user_ids = get_visible_user_ids(
        db,
        current_user,
        "evidence",
    )

    evidence = (
        db.query(Evidence)
        .join(
            Control,
            Evidence.control_id
            == Control.id,
        )
        .filter(
            Evidence.id == evidence_id,
            Control.owner_id.in_(
                visible_user_ids
            ),
        )
        .first()
    )

    if evidence is None:
        raise HTTPException(
            status_code=404,
            detail="Evidence not found.",
        )

    # Do not allow an API client to change the
    # server-managed physical path.
    update_data = evidence_data.model_dump(
        exclude_unset=True
    )

    if "file_path" in update_data:
        raise HTTPException(
            status_code=400,
            detail=(
                "Evidence file path cannot "
                "be changed directly."
            ),
        )

    updated_evidence = update_evidence(
        db,
        evidence_id,
        evidence_data,
    )

    if updated_evidence is None:
        raise HTTPException(
            status_code=404,
            detail="Evidence not found.",
        )

    return updated_evidence


@router.delete(
    "/{evidence_id}",
)
def delete_existing_evidence(
    evidence_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(
        require_permission(
            "evidence",
            "delete",
        )
    ),
):
    visible_user_ids = get_visible_user_ids(
        db,
        current_user,
        "evidence",
    )

    evidence = (
        db.query(Evidence)
        .join(
            Control,
            Evidence.control_id
            == Control.id,
        )
        .filter(
            Evidence.id == evidence_id,
            Control.owner_id.in_(
                visible_user_ids
            ),
        )
        .first()
    )

    if evidence is None:
        raise HTTPException(
            status_code=404,
            detail="Evidence not found.",
        )

    physical_path = Path(
        evidence.file_path
    )

    if not physical_path.is_absolute():
        physical_path = (
            Path.cwd() / physical_path
        )

    deleted = delete_evidence(
        db,
        evidence_id,
    )

    if deleted is None:
        raise HTTPException(
            status_code=404,
            detail="Evidence not found.",
        )

    try:
        resolved_path = (
            physical_path.resolve()
        )
        upload_root = (
            UPLOAD_DIR.resolve()
        )

        resolved_path.relative_to(
            upload_root
        )

        if resolved_path.is_file():
            resolved_path.unlink()

    except (ValueError, OSError):
        # Database deletion has already succeeded.
        # Never expose filesystem details to the client.
        pass

    return {
        "message": (
            "Evidence deleted successfully."
        ),
    }