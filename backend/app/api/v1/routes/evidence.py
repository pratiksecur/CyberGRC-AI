UPLOAD_DIR = Path("uploads")
UPLOAD_DIR.mkdir(
    parents=True,
    exist_ok=True,
)


router = APIRouter(
    prefix="/evidence",
    tags=["Evidence Management"],
)


def _validate_upload_metadata(
    file: UploadFile,
) -> str:
    """
    Validate the user-supplied upload metadata.

    The physical filename is generated by the server and
    therefore never depends on the original filename.
    """

    original_filename = (
        Path(file.filename or "")
        .name
        .strip()
    )

    if not original_filename:
        raise HTTPException(
            status_code=400,
            detail="A valid file name is required.",
        )

    if (
        original_filename in {".", ".."}
        or ".." in original_filename
    ):
        raise HTTPException(
            status_code=400,
            detail="Invalid file name.",
        )

    extension = (
        Path(original_filename)
        .suffix
        .lower()
    )

    if extension not in ALLOWED_UPLOAD_EXTENSIONS:
        raise HTTPException(
            status_code=400,
            detail="File type is not allowed.",
        )

    content_type = (
        file.content_type or ""
    ).lower()

    if content_type not in ALLOWED_UPLOAD_CONTENT_TYPES:
        raise HTTPException(
            status_code=400,
            detail="File content type is not allowed.",
        )

    return original_filename


def _build_storage_path(
    original_filename: str,
) -> Path:
    """
    Generate a non-user-controlled physical filename.
    """

    extension = (
        Path(original_filename)
        .suffix
        .lower()
    )

    generated_name = (
        f"{uuid4().hex}{extension}"
    )

    return UPLOAD_DIR / generated_name


def _save_upload(
    file: UploadFile,
    destination: Path,
) -> int:
    """
    Stream the uploaded file to disk while enforcing
    the configured maximum size.

    Returns the number of bytes written.
    """

    total_bytes = 0

    try:
        with destination.open("wb") as buffer:

            while True:
                chunk = file.file.read(
                    1024 * 1024
                )

                if not chunk:
                    break

                total_bytes += len(chunk)

                if (
                    total_bytes
                    > MAX_UPLOAD_SIZE_BYTES
                ):
                    raise HTTPException(
                        status_code=413,
                        detail=(
                            "Uploaded file exceeds "
                            "the maximum allowed size."
                        ),
                    )

                buffer.write(chunk)

    except HTTPException:
        if destination.exists():
            destination.unlink()

        raise

    except Exception:
        if destination.exists():
            destination.unlink()

        raise HTTPException(
            status_code=400,
            detail="Unable to store uploaded file.",
        )

    return total_bytes


@router.post(
    "/",
    response_model=EvidenceResponse,
)
def create_new_evidence(
    control_id: int = Form(...),
    title: str = Form(...),
    description: str = Form(...),
    file: UploadFile = File(...),
    db: Session = Depends(get_db),
    current_user: User = Depends(
        require_permission(
            "evidence",
            "create",
        )
    ),
):
    """
    Upload evidence for a control.

    Uploaded files are stored using server-generated names
    and can only be retrieved through the authorized
    evidence download endpoint.
    """

    control = (
        db.query(Control)
        .filter(
            Control.id == control_id
        )
        .first()
    )

    if control is None:
        raise HTTPException(
            status_code=404,
            detail="Control not found.",
        )

    ensure_user_in_scope(
        db,
        current_user,
        control.owner_id,
        "evidence",
    )

    original_filename = (
        _validate_upload_metadata(file)
    )

    destination = _build_storage_path(
        original_filename
    )

    _save_upload(
        file,
        destination,
    )

    relative_file_path = str(
        destination.as_posix()
    )

    evidence_data = EvidenceCreate(
        control_id=control_id,
        title=title,
        description=description,
        file_name=original_filename,
        file_path=relative_file_path,
    )

    try:
        evidence = create_evidence(
            db,
            evidence_data,
            current_user.id,
        )

    except Exception:
        if destination.exists():
            destination.unlink()

        raise

    if evidence is None:
        if destination.exists():
            destination.unlink()

        raise HTTPException(
            status_code=404,
            detail="Unable to create evidence.",
        )

    return evidence


@router.get(
    "/",
    response_model=list[EvidenceResponse],
)
def list_all_evidence(
    db: Session = Depends(get_db),
    current_user: User = Depends(
        require_permission(
            "evidence",
            "view",
        )
    ),
):
    visible_user_ids = get_visible_user_ids(
        db,
        current_user,
        "evidence",
    )

    return (
        db.query(Evidence)
        .join(
            Control,
            Evidence.control_id
            == Control.id,
        )
        .filter(
            Control.owner_id.in_(
                visible_user_ids
            )
        )
        .all()
    )


